import { readFileSync, writeFileSync } from 'node:fs';

const bmpBuf = readFileSync(new URL('../original/Font.bmp', import.meta.url));
const width = bmpBuf.readInt32LE(18);
const height = Math.abs(bmpBuf.readInt32LE(22));
const dataOffset = bmpBuf.readUInt32LE(10);

const rgba = Buffer.alloc(width * height * 4);
const rowBytes = width * 3; // 256 * 3 = 768 (already multiple of 4)

for (let y = 0; y < height; y++) {
  // BMP format stores scanlines bottom-up
  const bmpY = (height - 1) - y;
  const rowOffset = dataOffset + bmpY * rowBytes;
  for (let x = 0; x < width; x++) {
    const pxOffset = rowOffset + x * 3;
    const b = bmpBuf[pxOffset];
    const g = bmpBuf[pxOffset + 1];
    const r = bmpBuf[pxOffset + 2];
    const brightness = Math.round((r + g + b) / 3);
    const outOffset = (y * width + x) * 4;
    rgba[outOffset] = 255;
    rgba[outOffset + 1] = 255;
    rgba[outOffset + 2] = 255;
    rgba[outOffset + 3] = brightness;
  }
}

const fontBase64 = rgba.toString('base64');
const readmeText = readFileSync(new URL('../original/readme.txt', import.meta.url), 'utf8');

const output = `// Generated by npm run build; do not edit.
window.BRIDGE_FONT = {
  width: ${width},
  height: ${height},
  data: ${JSON.stringify(fontBase64)}
};
window.BRIDGE_README = ${JSON.stringify(readmeText)};
`;

writeFileSync(new URL('../web/font_assets.js', import.meta.url), output);
console.log(`Generated web/font_assets.js: Font ${width}x${height}, Readme ${readmeText.length} bytes`);
